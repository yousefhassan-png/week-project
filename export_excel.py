# ============================================================
# الملف 4: التصدير إلى Excel (الخطوة 4)
# ينتج ملف customer_analysis_report.xlsx بعدة صفحات + صفحة Summary
# ============================================================

import pandas as pd
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

from queries import جلب_كل_النتائج

اسم_ملف_الإكسل = "customer_analysis_report.xlsx"
النتائج = جلب_كل_النتائج()

# ---------- أسماء الصفحات (بالعربي) وما يقابلها من جداول ----------
أسماء_الصفحات = {
    "التفاصيل":         "تفاصيل_المبيعات",
    "أفضل_العملاء":     "أفضل_5_عملاء",
    "بدون_شراء":        "عملاء_بدون_شراء",
    "متوسط_الشراء":     "متوسط_الشراء",
    "ترتيب_المدن":      "ترتيب_داخل_المدن",
    "الاتجاه_الشهري":   "الاتجاه_الشهري",
    "الاتجاه_اليومي":   "الاتجاه_اليومي",
    "الفئات":           "أفضل_الفئات",
    "التسجيل_والإنفاق": "التسجيل_والإنفاق",
    "المتكررون":        "العملاء_المتكررون",
    "المدن":            "الإيراد_حسب_المدينة",
}

# ---------- 1) كتابة الجداول في ملف الإكسل ----------
الكاتب = pd.ExcelWriter(اسم_ملف_الإكسل, engine="openpyxl")
for مفتاح, اسم_الصفحة in أسماء_الصفحات.items():
    النتائج[مفتاح].to_excel(الكاتب, sheet_name=اسم_الصفحة, index=False)

الملف = الكاتب.book

# ---------- 2) تنسيق الصفحات ----------
خط_عادي = Font(name="Arial", size=11)
خط_العنوان = Font(name="Arial", size=11, bold=True, color="FFFFFF")
لون_العنوان = PatternFill("solid", fgColor="1F4E78")
حدود = Border(left=Side(style="thin", color="BBBBBB"), right=Side(style="thin", color="BBBBBB"),
              top=Side(style="thin", color="BBBBBB"), bottom=Side(style="thin", color="BBBBBB"))

# الكلمات التي تدل على أن العمود مبلغ مالي (لتنسيق الأرقام)
كلمات_المبالغ = ["إنفاق", "إيراد", "الإيراد", "قيمة", "سعر", "متوسط", "المتوسط", "الفرق"]

for اسم_الصفحة in أسماء_الصفحات.values():
    الصفحة = الملف[اسم_الصفحة]
    الصفحة.sheet_view.rightToLeft = True      # اتجاه الصفحة من اليمين لليسار
    الصفحة.freeze_panes = "A2"                # تثبيت صف العناوين
    for العمود in الصفحة.columns:
        أطول_نص = 0
        عنوان_العمود = str(العمود[0].value)
        for الخلية in العمود:
            الخلية.font = خط_عادي
            الخلية.border = حدود
            الخلية.alignment = Alignment(horizontal="center", vertical="center")
            if الخلية.value is not None:
                أطول_نص = max(أطول_نص, len(str(الخلية.value)))
            # تنسيق الأرقام للأعمدة المالية
            if الخلية.row > 1 and any(كلمة in عنوان_العمود for كلمة in كلمات_المبالغ):
                الخلية.number_format = "#,##0.00"
        الصفحة.column_dimensions[get_column_letter(العمود[0].column)].width = min(أطول_نص + 6, 40)
    for الخلية in الصفحة[1]:                  # صف العناوين
        الخلية.font = خط_العنوان
        الخلية.fill = لون_العنوان

# ---------- 3) حساب الأرقام المهمة للملخص التنفيذي ----------
جدول_التفاصيل = النتائج["التفاصيل"]
إجمالي_الإيراد = جدول_التفاصيل["قيمة_العملية"].sum()
عدد_العمليات = len(جدول_التفاصيل)
متوسط_العملية = إجمالي_الإيراد / عدد_العمليات
أول_تاريخ = جدول_التفاصيل["التاريخ"].min()
آخر_تاريخ = جدول_التفاصيل["التاريخ"].max()

جدول_أفضل = النتائج["أفضل_العملاء"]
إنفاق_أفضل_5 = جدول_أفضل["إجمالي_الإنفاق"].sum()
نسبة_أفضل_5 = 100 * إنفاق_أفضل_5 / إجمالي_الإيراد
اسم_أفضل_عميل = جدول_أفضل.iloc[0]["اسم_العميل"]
نسبة_أفضل_عميل = 100 * جدول_أفضل.iloc[0]["إجمالي_الإنفاق"] / إجمالي_الإيراد

جدول_الفئات = النتائج["الفئات"]
أفضل_فئة = جدول_الفئات.iloc[0]
أكثر_فئة_كمية = جدول_الفئات.sort_values("إجمالي_الكمية", ascending=False).iloc[0]

صف_المتكررين = النتائج["المتكررون"].iloc[0]
عدد_المتكررين = int(صف_المتكررين["العملاء_المتكررون"])
إجمالي_العملاء = int(صف_المتكررين["إجمالي_العملاء"])
عدد_بدون_شراء = int(صف_المتكررين["عملاء_بدون_شراء"])
نسبة_المتكررين = float(صف_المتكررين["نسبة_المتكررين_من_الكل"])
أسماء_بدون_شراء = "، ".join(النتائج["بدون_شراء"]["اسم_العميل"])

جدول_المدن = النتائج["المدن"]
أفضل_مدينة = جدول_المدن.iloc[0]
نسبة_أفضل_مدينة = 100 * أفضل_مدينة["إجمالي_الإيراد"] / إجمالي_الإيراد

جدول_المتوسط = النتائج["متوسط_الشراء"]
عدد_فوق_المتوسط = int((جدول_المتوسط["الحالة"] == "أعلى من المتوسط").sum())
عدد_المشترين = len(جدول_المتوسط)

جدول_اليومي = النتائج["الاتجاه_اليومي"]
أعلى_يوم = جدول_اليومي.sort_values("إيراد_اليوم", ascending=False).iloc[0]
نسبة_أعلى_يوم = 100 * أعلى_يوم["إيراد_اليوم"] / إجمالي_الإيراد

جدول_التسجيل = النتائج["التسجيل_والإنفاق"]
معامل_الارتباط = جدول_التسجيل["عدد_الأيام_منذ_التسجيل"].corr(جدول_التسجيل["إجمالي_الإنفاق"])

# ---------- 4) نص الملخص التنفيذي (بلغة الأعمال) ----------
نقاط_الملخص = [
    f"1) حقق المتجر إيراداً إجمالياً قدره {إجمالي_الإيراد:,.0f} من {عدد_العمليات} عملية بيع بين {أول_تاريخ} و {آخر_تاريخ}، بمتوسط {متوسط_العملية:,.0f} للعملية الواحدة.",
    f"2) الإيراد مركّز في عدد قليل من العملاء: أفضل 5 عملاء يشكّلون {نسبة_أفضل_5:.0f}% من الإيراد، وأفضل عميل ({اسم_أفضل_عميل}) وحده يشكّل {نسبة_أفضل_عميل:.0f}%. وفقط {عدد_فوق_المتوسط} من أصل {عدد_المشترين} عملاء يتجاوز متوسط قيمة شرائه المتوسط العام.",
    f"3) فئة ({أفضل_فئة['الفئة']}) هي المحرك الأساسي للإيراد بنسبة {أفضل_فئة['النسبة_من_الإيراد']:.0f}%، بينما فئة ({أكثر_فئة_كمية['الفئة']}) الأعلى في عدد الوحدات المباعة ({int(أكثر_فئة_كمية['إجمالي_الكمية'])} وحدة) لكنها قيمتها ضعيفة.",
    f"4) ولاء العملاء جيد: {عدد_المتكررين} من أصل {إجمالي_العملاء} عميلاً ({نسبة_المتكررين:.0f}%) اشتروا أكثر من مرة، في المقابل لدينا {عدد_بدون_شراء} من العملاء المسجلين لم يشتروا إطلاقاً ({أسماء_بدون_شراء}).",
    f"5) مدينة {أفضل_مدينة['المدينة']} تقود المبيعات بنسبة {نسبة_أفضل_مدينة:.0f}% من الإيراد.",
    f"6) أعلى يوم مبيعات كان {أعلى_يوم['التاريخ']} بنسبة {نسبة_أعلى_يوم:.0f}% من إيراد الفترة، وسببه صفقة واحدة كبيرة، أي أن الإيراد اليومي متذبذب ويعتمد على عدد قليل من الصفقات.",
    f"7) العملاء الأقدم يميلون إلى إنفاق أكبر (معامل الارتباط {معامل_الارتباط:.2f})، لكن جزءاً من ذلك سببه أنهم مسجلون منذ فترة أطول؛ حجم البيانات صغير ولا يكفي للجزم.",
    "توصية: إطلاق برنامج ولاء خاص لأفضل 5 عملاء لحمايتهم لأنهم يشكّلون الجزء الأكبر من الإيراد، وحملة تسويقية موجّهة للعملاء الذين لم يشتروا، مع عروض على الإلكترونيات المكمّلة (ملحقات الحاسوب) لرفع قيمة الشراء.",
    "ملاحظة: بيانات المبيعات تغطي شهراً واحداً فقط (سبتمبر 2026)، لذلك الاتجاه الشهري يحتوي نقطة واحدة، وتم دعمه بالاتجاه اليومي.",
]

# ---------- 5) صفحة Summary ----------
ملخص = الملف.create_sheet("Summary", 0)   # الصفحة الأولى
ملخص.sheet_view.rightToLeft = True
ملخص.column_dimensions["A"].width = 38
ملخص.column_dimensions["B"].width = 20
ملخص.column_dimensions["C"].width = 60

ملخص["A1"] = "ملخص تقرير تحليل العملاء والمبيعات"
ملخص["A1"].font = Font(name="Arial", size=16, bold=True, color="1F4E78")
ملخص.merge_cells("A1:C1")

# عناوين جدول الأرقام الرئيسية
for رقم_العمود, العنوان in enumerate(["المؤشر", "القيمة", "ملاحظة"], start=1):
    الخلية = ملخص.cell(row=3, column=رقم_العمود, value=العنوان)
    الخلية.font = خط_العنوان
    الخلية.fill = لون_العنوان
    الخلية.alignment = Alignment(horizontal="center")

# حدود النطاقات في الصفحات الأخرى (الصف 1 عناوين، فالبيانات تبدأ من الصف 2)
آخر_صف_مبيعات = len(جدول_التفاصيل) + 1
آخر_صف_عملاء = len(جدول_التسجيل) + 1
آخر_صف_أفضل = len(جدول_أفضل) + 1

# الأرقام الرئيسية: نستخدم معادلات إكسل حتى تتحدث الأرقام تلقائياً
# (الصف 4 = إجمالي الإيراد، الصف 7 = إجمالي العملاء، الصف 9 = المتكررون)
الأرقام_الرئيسية = [
    ("إجمالي الإيراد", f"=SUM('تفاصيل_المبيعات'!I2:I{آخر_صف_مبيعات})", "#,##0.00", "الكمية × سعر المنتج"),
    ("عدد عمليات البيع", f"=COUNTA('تفاصيل_المبيعات'!A2:A{آخر_صف_مبيعات})", "0", ""),
    ("متوسط قيمة العملية", f"=AVERAGE('تفاصيل_المبيعات'!I2:I{آخر_صف_مبيعات})", "#,##0.00", "المتوسط العام لقيمة الشراء"),
    ("إجمالي العملاء", f"=COUNTA('التسجيل_والإنفاق'!A2:A{آخر_صف_عملاء})", "0", ""),
    ("عملاء بدون أي شراء", f"=COUNTIF('التسجيل_والإنفاق'!E2:E{آخر_صف_عملاء},0)", "0", "مرشحون لحملة تسويقية"),
    ("العملاء المتكررون (أكثر من شراء)", f"=COUNTIF('التسجيل_والإنفاق'!E2:E{آخر_صف_عملاء},\">1\")", "0", ""),
    ("نسبة العملاء المتكررين", "=B9/B7", "0.0%", "من إجمالي العملاء"),
    ("حصة أفضل 5 عملاء من الإيراد", f"=SUM('أفضل_5_عملاء'!E2:E{آخر_صف_أفضل})/B4", "0.0%", "تركّز الإيراد"),
]
for رقم, (المؤشر, المعادلة, التنسيق, الملاحظة) in enumerate(الأرقام_الرئيسية):
    الصف = 4 + رقم
    ملخص.cell(row=الصف, column=1, value=المؤشر)
    خلية_القيمة = ملخص.cell(row=الصف, column=2, value=المعادلة)
    خلية_القيمة.number_format = التنسيق
    خلية_القيمة.alignment = Alignment(horizontal="center")
    ملخص.cell(row=الصف, column=3, value=الملاحظة)
    for العمود in (1, 2, 3):
        ملخص.cell(row=الصف, column=العمود).font = خط_عادي
        ملخص.cell(row=الصف, column=العمود).border = حدود

# الملخص التنفيذي
صف_البداية = 4 + len(الأرقام_الرئيسية) + 2
ملخص.cell(row=صف_البداية, column=1, value="الملخص التنفيذي").font = Font(name="Arial", size=13, bold=True, color="1F4E78")
for رقم, النقطة in enumerate(نقاط_الملخص, start=1):
    الصف = صف_البداية + رقم
    ملخص.cell(row=الصف, column=1, value=النقطة)
    ملخص.merge_cells(start_row=الصف, start_column=1, end_row=الصف, end_column=3)
    ملخص.cell(row=الصف, column=1).font = خط_عادي
    ملخص.cell(row=الصف, column=1).alignment = Alignment(wrap_text=True, vertical="top", horizontal="right")
    ملخص.row_dimensions[الصف].height = 48

# ---------- 6) الحفظ ----------
الكاتب.close()
print("تم إنشاء الملف:", اسم_ملف_الإكسل)
print("\n".join(نقاط_الملخص))
