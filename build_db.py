# ---------- 3) فتح الاتصال بالقاعدة ----------
الاتصال = sqlite3.connect(اسم_القاعدة)
المؤشر = الاتصال.cursor()

# ---------- 4) إنشاء جدول customers ----------
# نحذف الجدول القديم إن وُجد حتى نقدر نشغل الملف أكثر من مرة بدون مشاكل
المؤشر.execute("DROP TABLE IF EXISTS customers")
المؤشر.execute("""
    CREATE TABLE customers (
        customer_id   INTEGER PRIMARY KEY,
        customer_name TEXT,
        city          TEXT,
        signup_date   TEXT
    )
""")
المؤشر.executemany("INSERT INTO customers VALUES (?, ?, ?, ?)", قائمة_العملاء)

# ---------- 5) إضافة عمود customer_id لجدول sales ----------
# أولاً نتأكد إن العمود مو موجود من قبل
أعمدة_المبيعات = [عمود[1] for عمود in المؤشر.execute("PRAGMA table_info(sales)")]
if "customer_id" not in أعمدة_المبيعات:
    المؤشر.execute(
        "ALTER TABLE sales ADD COLUMN customer_id INTEGER REFERENCES customers(customer_id)"
    )

# ---------- 6) ربط كل عملية بيع بعميلها ----------
for رقم_البيع, رقم_العميل in توزيع_المبيعات.items():
    المؤشر.execute(
        "UPDATE sales SET customer_id = ? WHERE sale_id = ?",
        (رقم_العميل, رقم_البيع),
    )

الاتصال.commit()   # حفظ التغييرات

# ---------- 7) التحقق من النتيجة ----------
عدد_العملاء = المؤشر.execute("SELECT COUNT(*) FROM customers").fetchone()[0]
عدد_المبيعات_المربوطة = المؤشر.execute(
    "SELECT COUNT(*) FROM sales WHERE customer_id IS NOT NULL").fetchone()[0]
عدد_المبيعات_غير_المربوطة = المؤشر.execute(
    "SELECT COUNT(*) FROM sales WHERE customer_id IS NULL").fetchone()[0]
عدد_العملاء_بدون_شراء = المؤشر.execute("""
    SELECT COUNT(*) FROM customers
    WHERE customer_id NOT IN (SELECT customer_id FROM sales WHERE customer_id IS NOT NULL)
""").fetchone()[0]

print("عدد العملاء:", عدد_العملاء)
print("عمليات البيع المربوطة بعميل:", عدد_المبيعات_المربوطة)
