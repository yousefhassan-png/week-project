import sqlite3   # مكتبة للتعامل مع قاعدة بيانات SQLite
import os        # مكتبة للتحقق من وجود الملفات

اسم_القاعدة = "store.db"
اسم_ملف_النسخة = "store_db_dump.txt"   # النسخة النصية من القاعدة الأصلية

# ---------- 0) إذا ما في ملف store.db نبنيه من النسخة النصية ----------
if not os.path.exists(اسم_القاعدة):
    if os.path.exists(اسم_ملف_النسخة):
        print("ملف store.db غير موجود، سيتم بناؤه من النسخة النصية...")
        الاتصال_المؤقت = sqlite3.connect(اسم_القاعدة)
        with open(اسم_ملف_النسخة, encoding="utf-8") as الملف:
            الاتصال_المؤقت.executescript(الملف.read())
        الاتصال_المؤقت.close()
    else:
        print("خطأ: ضع ملف store.db أو store_db_dump.txt بجانب هذا الملف")
        raise SystemExit

