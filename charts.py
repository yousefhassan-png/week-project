import os
import matplotlib.pyplot as plt
import seaborn as sns
import plotly.express as px

from queries import جلب_كل_النتائج

# ---------- دعم اللغة العربية في الرسومات ----------
# المكتبتان: arabic-reshaper و python-bidi (لتوصيل الحروف وترتيبها من اليمين لليسار)
try:
    import arabic_reshaper
    from bidi.algorithm import get_display
    يوجد_دعم_العربية = True
except ImportError:
    يوجد_دعم_العربية = False
    print("تنبيه: ثبّت المكتبتين لتظهر الحروف العربية بشكل صحيح في الرسومات:")
    print("pip install arabic-reshaper python-bidi")


def نص_عربي(النص):
    """تجهّز النص العربي ليظهر صحيحاً داخل رسومات Matplotlib و Seaborn"""
    if يوجد_دعم_العربية:
        return get_display(arabic_reshaper.reshape(str(النص)))
    return str(النص)


# إعدادات عامة: خط يدعم العربية (Tahoma أو Arial موجودان في ويندوز)
plt.rcParams["font.family"] = ["Tahoma", "Arial", "DejaVu Sans"]
plt.rcParams["axes.unicode_minus"] = False
sns.set_theme(style="whitegrid", font=["Tahoma", "Arial", "DejaVu Sans"])

# مجلد حفظ الرسومات
مجلد_الرسومات = "charts"
os.makedirs(مجلد_الرسومات, exist_ok=True)

# جلب نتائج الاستعلامات
النتائج = جلب_كل_النتائج()


# ============================================================
# الرسمة 1 (Matplotlib): أفضل 5 عملاء من ناحية الإنفاق
# ============================================================
جدول_أفضل = النتائج["أفضل_العملاء"].sort_values("إجمالي_الإنفاق")   # ترتيب تصاعدي ليظهر الأكبر في الأعلى
أسماء_العملاء = [نص_عربي(اسم) for اسم in جدول_أفضل["اسم_العميل"]]

الشكل1, المحور1 = plt.subplots(figsize=(9, 5))
الأعمدة1 = المحور1.barh(أسماء_العملاء, جدول_أفضل["إجمالي_الإنفاق"], color="#2E86AB")
المحور1.bar_label(الأعمدة1, fmt="%.0f", padding=3)   # كتابة القيمة بجانب كل عمود
المحور1.set_title(نص_عربي("أفضل 5 عملاء من ناحية إجمالي الإنفاق"), fontsize=14)
المحور1.set_xlabel(نص_عربي("إجمالي الإنفاق"))
المحور1.set_xlim(0, جدول_أفضل["إجمالي_الإنفاق"].max() * 1.15)
plt.tight_layout()
plt.savefig(f"{مجلد_الرسومات}/1_أفضل_5_عملاء.png", dpi=150)
plt.close()


# ============================================================
# الرسمة 2 (Seaborn): الإيراد حسب فئة المنتجات
# ============================================================
جدول_الفئات = النتائج["الفئات"].copy()
جدول_الفئات["الفئة_للعرض"] = جدول_الفئات["الفئة"].apply(نص_عربي)

الشكل2, المحور2 = plt.subplots(figsize=(8, 5))
sns.barplot(data=جدول_الفئات, x="الفئة_للعرض", y="إجمالي_الإيراد",
            hue="الفئة_للعرض", palette="viridis", legend=False, ax=المحور2)
for الأعمدة in المحور2.containers:
    المحور2.bar_label(الأعمدة, fmt="%.0f", padding=3)
المحور2.set_title(نص_عربي("الإيراد حسب فئة المنتجات"), fontsize=14)
المحور2.set_xlabel(نص_عربي("الفئة"))
المحور2.set_ylabel(نص_عربي("إجمالي الإيراد"))
plt.tight_layout()
plt.savefig(f"{مجلد_الرسومات}/2_الإيراد_حسب_الفئة.png", dpi=150)
plt.close()


# ============================================================
# الرسمة 3 (Plotly - تفاعلية): الاتجاه اليومي للإيراد
# ============================================================
جدول_يومي = النتائج["الاتجاه_اليومي"]
الشكل3 = px.line(
    جدول_يومي, x="التاريخ", y="إيراد_اليوم", markers=True,
    title="الاتجاه اليومي للإيراد (سبتمبر 2026)",
    hover_data=["الإيراد_التراكمي"],
)
الشكل3.update_layout(font=dict(family="Tahoma, Arial", size=14))
الشكل3.write_html(f"{مجلد_الرسومات}/3_الاتجاه_اليومي_تفاعلي.html")


# ============================================================
# الرسمة 4 (Seaborn): العلاقة بين مدة التسجيل وحجم الإنفاق
# ============================================================
جدول_التسجيل = النتائج["التسجيل_والإنفاق"]
معامل_الارتباط = جدول_التسجيل["عدد_الأيام_منذ_التسجيل"].corr(جدول_التسجيل["إجمالي_الإنفاق"])

الشكل4, المحور4 = plt.subplots(figsize=(8, 5))
sns.regplot(data=جدول_التسجيل, x="عدد_الأيام_منذ_التسجيل", y="إجمالي_الإنفاق",
            color="#E07A5F", ax=المحور4)
المحور4.set_title(نص_عربي(f"مدة التسجيل مقابل الإنفاق (معامل الارتباط = {معامل_الارتباط:.2f})"), fontsize=13)
المحور4.set_xlabel(نص_عربي("عدد الأيام منذ التسجيل"))
المحور4.set_ylabel(نص_عربي("إجمالي الإنفاق"))
plt.tight_layout()
plt.savefig(f"{مجلد_الرسومات}/4_التسجيل_والإنفاق.png", dpi=150)
plt.close()


# ============================================================
# الرسمة 5 (Matplotlib): تصنيف العملاء حسب عدد المشتريات
# ============================================================
صف_المتكررين = النتائج["المتكررون"].iloc[0]
قيم_الأقسام = [
    صف_المتكررين["العملاء_المتكررون"],
    صف_المتكررين["عملاء_اشتروا_مرة_واحدة"],
    صف_المتكررين["عملاء_بدون_شراء"],
]
أسماء_الأقسام = [نص_عربي("عملاء متكررون"), نص_عربي("اشتروا مرة واحدة"), نص_عربي("لم يشتروا")]

الشكل5, المحور5 = plt.subplots(figsize=(7, 6))
المحور5.pie(قيم_الأقسام, labels=أسماء_الأقسام, autopct="%1.1f%%", startangle=90,
            colors=["#3D9970", "#F4A261", "#E63946"])
المحور5.set_title(نص_عربي("تصنيف العملاء حسب عدد مرات الشراء"), fontsize=14)
plt.tight_layout()
plt.savefig(f"{مجلد_الرسومات}/5_تصنيف_العملاء.png", dpi=150)
plt.close()


# ============================================================
# الرسمة 6 (Plotly - تفاعلية): إنفاق العملاء داخل كل مدينة
# ============================================================
الشكل6 = px.bar(
    النتائج["ترتيب_المدن"], x="اسم_العميل", y="إجمالي_الإنفاق", color="المدينة",
    title="إنفاق العملاء داخل كل مدينة",
    hover_data=["الترتيب_داخل_المدينة"],
)
الشكل6.update_layout(font=dict(family="Tahoma, Arial", size=14))
الشكل6.write_html(f"{مجلد_الرسومات}/6_الإنفاق_حسب_المدينة_تفاعلي.html")


print("تم حفظ الرسومات الستة في مجلد:", مجلد_الرسومات)
print("معامل الارتباط بين مدة التسجيل والإنفاق:", round(معامل_الارتباط, 2))
